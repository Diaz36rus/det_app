def workshop_for(category: str, name: str) -> str:
    blob = f"{category} {name}".lower()
    if "химчист" in blob:
        return "Химчистка"
    if any(x in blob for x in ("полир", "керамик", "силант", "антидожд", "krytex")):
        return "Полировка"
    if any(x in blob for x in ("оклей", "пленк", "плёнк", "тонир")):
        return "Оклейка"
    if any(x in blob for x in ("интерьер", "салон", "уборк")) and "хим" not in blob:
        # «Детейлинг уборка салона» / багажник — см. ниже
        if "детейлинг" in blob or "уборка салона" in blob:
            return "Интерьер"
    if "двигател" in blob or "оборуд" in blob:
        return "Оборудование"
    if "мойк" in blob or "багаж" in blob:
        return "Мойка"
    if category == "Мойка":
        return "Мойка"
    if category == "Химчистка":
        return "Химчистка"
    if category in ("Полировка", "Керамика и Силант", "Антидождь"):
        return "Полировка"
    if category in ("Оклейка (Пленка)", "Тонировка"):
        return "Оклейка"
    return ""


def cloud_price(p1: float, p2: float, p3: float, p4: float, fp: float) -> float:
    if fp and fp > 0:
        return float(fp)
    for p in (p1, p2, p3, p4):
        if p and p > 0:
            return float(p)
    return 0.0


def iter_price_catalog() -> list[dict]:
    """Список услуг для seed / sync: name, category, price, workshop."""
    out: list[dict] = []
    for cat, name, p1, p2, p3, p4, fp in _CORE:
        out.append(
            {
                "category": cat,
                "name": name,
                "price": cloud_price(p1, p2, p3, p4, fp),
                "workshop": workshop_for(cat, name),
            }
        )
    for name in _WRAP_NAMES:
        cat = "Оклейка (Пленка)"
        out.append(
            {
                "category": cat,
                "name": name,
                "price": 0.0,
                "workshop": "Оклейка",
            }
        )
    return out
